"""Export the recorded agent run and contained-unit presentation, without network."""
from pathlib import Path
import gzip
import hashlib
import json
import shutil

BASE = Path(__file__).resolve().parent
ROOT = BASE.parent
SITE = BASE / 'site'
LABEL = 'one unit in a larger building; not placed on the aerial photo'


def contained(row):
    try:
        return row.get('poor') == 'True' and float(row['registration_iou']) < .55 and float(row['registration_containment']) >= .9
    except (KeyError, ValueError, TypeError):
        return False


def export_replay():
    source = ROOT / 'data/claims/eval/dry_run_trace.json'
    source_bytes = source.read_bytes()
    trace = json.loads(source_bytes)
    assert trace['real_model_run'] is False and trace['passed'] is True
    workspace = (ROOT / trace['workspace']).resolve()
    assert workspace.is_relative_to(ROOT / 'data/claims/workspaces')
    files = {}
    for path in sorted(workspace.rglob('*')):
        if not path.resolve().is_relative_to(workspace) or not path.is_file() or path.stat().st_size > 2_000_000:
            continue
        relative = path.relative_to(workspace).as_posix()
        if path.suffix in ('.json', '.md', '.csv', '.txt'):
            files[relative] = {'text': path.read_text()}
        elif path.suffix == '.png':
            target = SITE / 'replay' / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            saved_image = BASE / 'cache/round3-checkpoint/replay' / relative
            if target.exists() and not saved_image.exists():
                saved_image.parent.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(target, saved_image)
            shutil.copyfile(path, target)
            files[relative] = {'image': 'replay/' + relative}
    bundle = dict(trace, files=files, source=str(source.relative_to(ROOT)),
                  source_sha256=hashlib.sha256(source_bytes).hexdigest())
    target = SITE / 'data/agent-replay.json'
    checkpoint = BASE / 'cache/round3-checkpoint/agent-replay.json'
    if target.exists() and not checkpoint.exists():
        checkpoint.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(target, checkpoint)
    target.write_text(json.dumps(bundle, ensure_ascii=False, separators=(',', ':')))
    result = {'trace_sha256': bundle['source_sha256'], 'events': len(trace['events']), 'workspace_files': len(files), 'bytes': target.stat().st_size}
    report_path = BASE / 'round3_data_report.json'
    if report_path.exists():
        saved_report = BASE / 'cache/round3-checkpoint/round3_data_report.json'
        if not saved_report.exists():
            shutil.copyfile(report_path, saved_report)
        report = json.loads(report_path.read_text())
        report.update(result)
        report_path.write_text(json.dumps(report, indent=2))
    return result


def main():
    proposal = json.loads((ROOT / 'data/facts/registration_followup/category_proposal.json').read_text())
    assert proposal['criteria'] == 'Existing poor AND IoU < 0.55 AND containment >= 0.90'
    index_path = SITE / 'data/index.json'
    checkpoint = BASE / 'cache/round3-checkpoint'
    checkpoint.mkdir(parents=True, exist_ok=True)
    if not (checkpoint / 'index.json').exists():
        shutil.copyfile(index_path, checkpoint / 'index.json')
    index = json.loads(index_path.read_text())
    selected = []
    for home in index['homes']:
        path = SITE / 'data' / (home['sid'] + '.json.gz')
        data = json.loads(gzip.decompress(path.read_bytes()))
        partial = contained(data['selection'])
        home['contained_partial'] = partial
        if partial:
            assert home['placement'] != 'well' and not home['sun']
            selected.append(home['sid'])
        if bool(data.get('contained_partial')) == partial:
            continue
        # Snapshot generated bytes before writing; source edits use apply_patch.
        saved = checkpoint / path.name
        if not saved.exists():
            shutil.copyfile(path, saved)
        data['contained_partial'] = partial
        path.write_bytes(gzip.compress(json.dumps(data, separators=(',', ':'), ensure_ascii=False).encode(), compresslevel=5, mtime=0))
    index_path.write_text(json.dumps(index, separators=(',', ':'), ensure_ascii=False))
    report = dict(export_replay(), contained_partial_count=len(selected), contained_partial_sids=selected,
                  criteria=proposal['criteria'], label=LABEL, sun_policy='Existing poor flag and withholding unchanged')
    (BASE / 'round3_data_report.json').write_text(json.dumps(report, indent=2))
    print(json.dumps({k:v for k,v in report.items() if k != 'contained_partial_sids'}, indent=2))


if __name__ == '__main__':
    main()
